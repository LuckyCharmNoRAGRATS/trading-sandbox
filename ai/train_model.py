import os
import sys
import joblib
from pathlib import Path
import pandas as pd
import numpy as np
from sklearn.ensemble import RandomForestClassifier
from sklearn.model_selection import TimeSeriesSplit
from sklearn.metrics import classification_report, accuracy_score

# Ensure root modules are importable
ROOT_DIR = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT_DIR))

from quant_engine import DataLayer, SMACrossover
from ai.triple_barrier import TripleBarrierLabeler
from ai.meta_labeler import MetaLabelFilter

MODEL_DIR = ROOT_DIR / "models"
MODEL_DIR.mkdir(exist_ok=True)
MODEL_PATH = MODEL_DIR / "rf_meta_model.pkl"

def train_purged_model(symbol: str = "SPY", days: int = 1500):
    print(f"--- FETCHING DATA FOR {symbol} ---")
    data_layer = DataLayer()
    df = data_layer.get_bars(symbol=symbol, days=days)
    
    if len(df) < 500:
        print("⚠️ Insufficient data for ML training. Minimum 500 bars required.")
        return

    # 1. Generate Trading Signals (The "Base Model")
    strategy = SMACrossover(fast_window=20, slow_window=50)
    df['signal'] = strategy.generate_signals(df)
    
    # 2. Generate Triple Barrier Labels (The Target 'y')
    # Assumes a 2% profit target, 1% stop loss, and max hold of 10 days
    labeler = TripleBarrierLabeler(profit_target_pct=0.02, stop_loss_pct=0.01, max_hold_bars=10)
    df = labeler.apply_barriers(df, signal_col='signal')
    
    # 3. Generate ML Features (The Input 'X')
    features = MetaLabelFilter.generate_features(df)
    
    # Merge features and labels, keeping only rows where a trade was initiated
    dataset = pd.concat([features, df[['signal', 'target_label']]], axis=1).dropna()
    dataset = dataset[dataset['signal'] != 0].copy()
    
    if dataset.empty:
        print("❌ No signals generated by the base strategy. Cannot train meta-labeler.")
        return
        
    X = dataset[['returns_1d', 'returns_5d', 'volatility_20d', 'price_to_sma', 'hurst']]
    
    # Convert labels: 1 (Hit Profit Target) becomes 1, everything else (-1 or 0) becomes 0
    y = np.where(dataset['target_label'] == 1, 1, 0)
    
    print(f"Total Training Samples (Trades Executed): {len(X)}")
    print(f"Target Class Distribution: {np.bincount(y)}")

    # 4. Purged Time Series Cross-Validation
    # Gap equals the maximum holding period to prevent data leakage
    tscv = TimeSeriesSplit(n_splits=5, gap=10)
    
    clf = RandomForestClassifier(
        n_estimators=100, 
        max_depth=5, 
        random_state=42, 
        class_weight="balanced"
    )
    
    print("\n--- PURGED CROSS-VALIDATION ---")
    fold = 1
    accuracies = []
    
    for train_index, test_index in tscv.split(X):
        X_train, X_test = X.iloc[train_index], X.iloc[test_index]
        y_train, y_test = y[train_index], y[test_index]
        
        clf.fit(X_train, y_train)
        y_pred = clf.predict(X_test)
        
        acc = accuracy_score(y_test, y_pred)
        accuracies.append(acc)
        print(f"Fold {fold} Accuracy: {acc:.2%}")
        fold += 1
        
    print(f"Average Out-of-Sample Accuracy: {np.mean(accuracies):.2%}")

    # 5. Train Final Production Model on 100% of the dataset
    clf.fit(X, y)
    
    # 6. Serialize and Export
    joblib.dump(clf, MODEL_PATH)
    print(f"\n✅ Final Meta-Labeling Model saved to {MODEL_PATH}")

if __name__ == "__main__":
    train_purged_model(symbol="SPY", days=1500)